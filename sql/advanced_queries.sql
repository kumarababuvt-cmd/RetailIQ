========================================================
TOP CUSTOMER BY REVENUE IN EACH STORE
(ADVANCED SQL - CTE + WINDOW FUNCTION)
========================================================

Purpose:
Identify the customer who generated the highest revenue
within each store.

Formula:
Revenue =
SUM(Quantity × Unit Price)

Technique Used:
1. Aggregate customer revenue for each store.
2. Use ROW_NUMBER() to rank customers within each store.
3. PARTITION BY Store.
4. ORDER BY Revenue DESC.
