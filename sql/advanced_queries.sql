/*
========================================================
RUNNING MONTHLY REVENUE
(ADVANCED SQL - CTE + WINDOW FUNCTION)
========================================================

Purpose:
Calculate the cumulative (running) sales revenue
month by month throughout the year.

Formula:
Monthly Revenue =
SUM(Quantity × Unit Price)

Running Revenue =
SUM(Monthly Revenue) OVER (ORDER BY Month)

Technique Used:
1. Aggregate revenue for each month.
2. Store monthly revenue in a CTE.
3. Apply a running total using SUM() OVER().
4. Order by month number to maintain chronological order.

Business Use:
This analysis helps RetailIQ monitor cumulative
business growth throughout the year. It is useful
for revenue tracking, financial reporting, trend
analysis, forecasting, and executive dashboards.

Window Function Used:
SUM() OVER()

Reason:
Calculates a cumulative running total without
collapsing rows, making it ideal for trend analysis.

========================================================
*/

WITH monthly_revenue AS
(
    SELECT
        MONTH(o.order_date) AS month_number,
        MONTHNAME(o.order_date) AS month_name,

        SUM(oi.quantity * oi.unit_price) AS monthly_revenue

    FROM orders o

    JOIN order_items oi
        ON o.order_id = oi.order_id

    GROUP BY
        MONTH(o.order_date),
        MONTHNAME(o.order_date)
)

SELECT
    month_name,
    monthly_revenue,

    SUM(monthly_revenue) OVER
    (
        ORDER BY month_number
    ) AS running_revenue

FROM monthly_revenue

ORDER BY month_number;

/*
========================================================
MONTH-OVER-MONTH REVENUE GROWTH
(ADVANCED SQL - CTE + WINDOW FUNCTION)
========================================================

Purpose:
Calculate the month-over-month revenue growth by
comparing each month's revenue with the previous month.

Formula:
Monthly Revenue =
SUM(Quantity × Unit Price)

Growth % =
((Current Revenue - Previous Revenue)
 / Previous Revenue) × 100

Technique Used:
1. Aggregate monthly revenue in a CTE.
2. Use LAG() to retrieve the previous month's revenue.
3. Calculate the percentage growth between consecutive months.
4. Order by month number to maintain chronological order.

Business Use:
This analysis helps RetailIQ monitor business growth
over time, identify seasonal trends, evaluate sales
performance, and support forecasting and strategic
planning.

Window Function Used:
LAG()

Reason:
Retrieves the previous month's revenue without using
self-joins or subqueries, making month-over-month
comparisons simple and efficient.

========================================================
*/

WITH monthly_revenue AS
(
    SELECT
        MONTH(o.order_date) AS month_number,
        MONTHNAME(o.order_date) AS month_name,

        SUM(oi.quantity * oi.unit_price) AS total_revenue

    FROM orders o

    JOIN order_items oi
        ON o.order_id = oi.order_id

    GROUP BY
        MONTH(o.order_date),
        MONTHNAME(o.order_date)
)

SELECT
    month_name,
    total_revenue,

    LAG(total_revenue) OVER
    (
        ORDER BY month_number
    ) AS previous_month_revenue,

    ROUND
    (
        (
            total_revenue
            -
            LAG(total_revenue) OVER(ORDER BY month_number)
        )
        /
        LAG(total_revenue) OVER(ORDER BY month_number)
        *100,
        2
    ) AS growth_percentage

FROM monthly_revenue

ORDER BY month_number;
