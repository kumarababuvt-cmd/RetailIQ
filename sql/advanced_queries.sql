WITH high_customer_cte AS
(
    SELECT
        s.store_id,
        s.store_location,
        c.customer_id,
        c.name AS customer_name,

        SUM(oi.quantity * oi.unit_price) AS total_revenue,

        ROW_NUMBER() OVER
        (
            PARTITION BY s.store_id
            ORDER BY SUM(oi.quantity * oi.unit_price) DESC
        ) AS row_num

    FROM store s

    JOIN orders o
        ON s.store_id = o.store_id

    JOIN customer c
        ON o.customer_id = c.customer_id

    JOIN order_items oi
        ON o.order_id = oi.order_id

    GROUP BY
        s.store_id,
        s.store_location,
        c.customer_id,
        c.name
)

SELECT
    store_location,
    customer_name,
    total_revenue
FROM high_customer_cte
WHERE row_num = 1
ORDER BY store_location;

