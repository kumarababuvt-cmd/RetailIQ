/*
========================================================
TOP SELLING PRODUCT IN EACH CATEGORY
(ADVANCED SQL - CTE + WINDOW FUNCTION)
========================================================

Purpose:
Identify the highest revenue-generating product within
each product category.

Formula:
Revenue =
SUM(Quantity × Unit Price)

Technique Used:
1. Aggregate revenue for each product.
2. Use ROW_NUMBER() to rank products within each category.
3. PARTITION BY Category.
4. ORDER BY Revenue DESC.
5. Filter Rank = 1.

Business Use:
This analysis helps RetailIQ identify the best-selling
product in every category. The results support
inventory planning, product promotion, pricing
strategies, and category performance analysis.

Window Function Used:
ROW_NUMBER()

Reason:
Returns exactly ONE highest revenue product
from each category.

========================================================
*/

WITH top_products AS
(
    SELECT
        c.category_id,
        c.category_name,
        p.product_id,
        p.model,
        SUM(oi.quantity * oi.unit_price) AS total_revenue,

        ROW_NUMBER() OVER
        (
            PARTITION BY c.category_id
            ORDER BY SUM(oi.quantity * oi.unit_price) DESC
        ) AS row_num

    FROM category c

    JOIN product p
        ON c.category_id = p.category_id

    JOIN order_items oi
        ON p.product_id = oi.product_id

    GROUP BY
        c.category_id,
        c.category_name,
        p.product_id,
        p.model
)

SELECT
    category_name,
    model,
    total_revenue
FROM top_products
WHERE row_num = 1
ORDER BY category_name;

